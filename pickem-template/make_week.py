#!/usr/bin/env python3
"""Build a weekly pickem page from a graphic + a small JSON file.

    python make_week.py week7.json            # builds the week7/ folder
    python make_week.py week7.json --check    # draws crop boxes on your graphic first
"""
import argparse, colorsys, html, json, os, sys
from PIL import Image, ImageDraw

REF_W = 1348  # boxes below are measured on a graphic that is 1348px wide; other sizes scale automatically
HERO = (62, 62, 1284, 360)
# order: MOTW inset, row 2 left, row 2 right, row 3 left, row 3 right -> (box, x where left image ends)
STRIPS = [((360, 362, 980, 498), 672), ((58, 527, 657, 660), 358), ((690, 527, 1290, 658), 990),
          ((58, 707, 657, 840), 358), ((690, 707, 1290, 838), 990)]

def ordinal(n):
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"

def lum(c):
    f = lambda v: v / 255 / 12.92 if v / 255 <= .03928 else ((v / 255 + .055) / 1.055) ** 2.4
    return .2126 * f(c[0]) + .7152 * f(c[1]) + .0722 * f(c[2])

def contrast(a, b):
    x, y = sorted([lum(a), lum(b)], reverse=True)
    return (x + .05) / (y + .05)

def pick_colors(img):
    """Light, vivid fill + darker stroke, both taken from the image's own palette."""
    q = img.convert('RGB').resize((120, 40)).quantize(8)
    pal = q.getpalette()
    cols = [tuple(pal[i * 3:i * 3 + 3]) for _, i in q.getcolors()]
    best, score = None, -1
    for f in cols:
        for s in cols:
            if lum(f) <= lum(s) or contrast(f, s) < 4.5:
                continue
            sat = colorsys.rgb_to_hsv(*[v / 255 for v in f])[1]
            sc = min(contrast(f, s), 9) + 10 * sat + 3 * lum(f)
            if sc > score:
                best, score = (f, s), sc
    hx = lambda c: '#%02x%02x%02x' % c
    return (hx(best[0]), hx(best[1])) if best else ('#ffffff', '#000000')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('config')
    ap.add_argument('--check', action='store_true', help='only draw the crop boxes on the graphic')
    ap.add_argument('--out', help='output folder (default: weekN next to the config)')
    a = ap.parse_args()
    base = os.path.dirname(os.path.abspath(a.config))
    cfg = json.load(open(a.config, encoding='utf-8'))
    group, week = cfg.get('group', 'TBSWHP'), cfg['week']
    title = cfg.get('title', f'{group} Week {week} Pickem')
    im = Image.open(os.path.join(base, cfg['graphic'])).convert('RGB')
    k = im.width / REF_W
    lay = cfg.get('layout', {})
    hero_box = lay.get('hero', HERO)
    strips = [(s['box'], s['split']) for s in lay['strips']] if 'strips' in lay else STRIPS
    S = lambda b: tuple(round(v * k) for v in b)
    ms = cfg['matchups']
    if len(ms) != len(strips):
        sys.exit(f'Expected {len(strips)} matchups, found {len(ms)}')

    if a.check:
        d = ImageDraw.Draw(im)
        d.rectangle(S(hero_box), outline='red', width=4)
        for n, (b, sx) in enumerate(strips, 1):
            x0, y0, x1, y1 = S(b)
            d.rectangle((x0, y0, x1, y1), outline='red', width=4)
            d.line((round(sx * k), y0, round(sx * k), y1), fill='lime', width=4)
            d.text((x0 + 8, y0 + 8), str(n), fill='yellow')
        p = os.path.join(base, 'layout-check.png'); im.save(p); print('Wrote', p); return

    out = a.out or os.path.join(base, f'week{week}')
    os.makedirs(os.path.join(out, 'img'), exist_ok=True)
    im.crop(S(hero_box)).save(os.path.join(out, 'img', 'hero.jpg'), quality=86)
    prev = im.copy(); prev.thumbnail((1200, 1200)); prev.save(os.path.join(out, 'preview.jpg'), quality=88)

    data = []
    for n, (m, (b, sx)) in enumerate(zip(ms, strips), 1):
        x0, y0, x1, y1 = S(b); cut = round(sx * k)
        im.crop((x0, y0, x1, y1)).save(os.path.join(out, 'img', f'm{n}.jpg'), quality=86)
        row = {'img': f'img/m{n}.jpg', 'split': round((cut - x0) / (x1 - x0) * 100, 2),
               'ar': round((x1 - x0) / (y1 - y0), 4)}
        for side, box in (('left', (x0, y0, cut, y1)), ('right', (cut, y0, x1, y1))):
            t = m[side]; fill, stroke = pick_colors(im.crop(box))
            row[side[0]] = {'seed': t['seed'], 'name': t['name'],
                            'record': f"{t['record']} | {ordinal(t['seed'])}",
                            'fill': t.get('fill', fill), 'stroke': t.get('stroke', stroke)}
        data.append(row)
    wk = {'group': group, 'week': week, 'title': title, 'hero': 'img/hero.jpg', 'matchups': data}
    open(os.path.join(out, 'week.js'), 'w', encoding='utf-8').write(
        '// Generated by make_week.py. Colors can be hand-edited.\nwindow.WEEK = ' + json.dumps(wk, indent=1, ensure_ascii=False) + ';\n')

    site = cfg.get('siteUrl', '').rstrip('/')
    meta = ['<meta name="theme-color" content="#161616">']
    if site and 'YOUR-' not in site:
        url = f'{site}/week{week}/'
        meta += ['<meta property="og:type" content="website">',
                 f'<meta property="og:title" content="{html.escape(title)}">',
                 '<meta property="og:description" content="Pick your winners for all 5 matchups. Tap a side to lock it in.">',
                 f'<meta property="og:image" content="{url}preview.jpg">', f'<meta property="og:url" content="{url}">',
                 '<meta name="twitter:card" content="summary_large_image">']
    else:
        print('WARNING: set a real "siteUrl" in the config or Discord will show no preview image.')
    tpl = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'page_template.html'), encoding='utf-8').read()
    open(os.path.join(out, 'index.html'), 'w', encoding='utf-8').write(
        tpl.replace('__META__', '\n'.join(meta)).replace('__TITLE__', html.escape(title)))
    print('Built', out)

if __name__ == '__main__':
    main()
